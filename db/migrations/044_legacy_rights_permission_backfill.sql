-- Legacy right_code -> permission backfill (Phase R security rights fix).
--
-- All rows migrated into group_rights by 009_legacy_security_rights.sql /
-- 019_security_data_import_adaptation.sql carry `permission IS NULL`, so
-- loadOperatorAccess's COALESCE(g.permission, g.right_code) falls back to
-- the raw numeric legacy RightCode, which never matches any of the modern
-- permission strings requirePermission() gates on. That leaves the three
-- non-admin legacy groups (REMOTE, SALES OFFICER, SHIFT INCHARGE) with no
-- working permissions at all -- see
-- docs/PHASE_R_SECURITY_RIGHTS_VERIFICATION_2026-08-08.md for the original
-- finding.
--
-- This migration backfills group_rights.permission using the reviewed,
-- human-auditable RightCode -> permission table in
-- services/api/internal/httpapi/legacy_rights_mapping.go (the two must be
-- regenerated together; this file is not hand-maintained independently of
-- that table). 433 of the 486 distinct legacy RightCodes found in dbo.Rights
-- have a confident modern-permission equivalent and are listed below; the
-- remaining 53 (Transactions/Accounting Vouchers, Payroll, E-Prescription,
-- Patient/Student modules, and a handful of genuinely ambiguous read/write
-- toggles) are intentionally absent so their group_rights.permission stays
-- NULL rather than being guessed.
--
-- The UPDATE is tenant-agnostic (keyed only by right_code) and idempotent:
-- it only touches rows whose permission is still unset, so re-running it
-- (e.g. after a future re-import) is safe and touches nothing once applied.
-- ADMINISTRATOR's bypass in hasTenantAdminRole is untouched by this change
-- (that group never consults group_rights for enforcement); this backfill
-- only affects the three non-admin legacy groups' actual permission grants.
--
-- group_rights has FORCE ROW LEVEL SECURITY; this backfill is intentionally
-- tenant-agnostic (it must reach every tenant's migrated rows), matching the
-- app.authenticating escape hatch already used by 009_legacy_security_rights.sql.
-- ops/postgres/apply-migrations.sh runs each file with plain autocommit
-- psql --file (no wrapping transaction and no session-scoped temp table
-- across statements), so this stays a single UPDATE ... FROM (VALUES ...)
-- statement rather than a populate-then-join temp table.

